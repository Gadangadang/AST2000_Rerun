"""
Numbers for the papers.

Every part writes the values its paper quotes into paper/results.tex next to
the running script (e.g. "Project 1/paper/results.tex"), as

    \\setvalue{launch-duration}{361.2}

and the paper prints them with \\val{launch-duration} (defined in
common/paper/ast2000.sty). So the papers never contain a hand-copied number:
rerun a part (or run_all.py with another seed) and recompile, and the text
follows. A missing key shows up in the PDF as a bold red ??key.

    from common.report import record
    record("launch-duration", 361.2, "{:.1f}")
    record("verified", "yes")

Values are kept in paper/results.json as well, so a part can be rerun in
pieces (e.g. engine.py alone) without losing what the other modules wrote.
"""
import json
import os
import re
import sys

import numpy as np

_main = getattr(sys.modules.get("__main__"), "__file__", None)
PAPER_DIR = os.path.join(os.path.dirname(os.path.abspath(_main)) if _main else os.getcwd(), "paper")
JSON_FILE = os.path.join(PAPER_DIR, "results.json")
TEX_FILE = os.path.join(PAPER_DIR, "results.tex")
_KEY = re.compile(r"^[A-Za-z][A-Za-z0-9-]*$")


def latex_number(text):
    """'1.23e-05' -> '1.23\\times10^{-5}' (inside math mode via \\ensuremath); plain numbers pass through."""
    match = re.fullmatch(r"(-?[\d.]+)e([+-]?\d+)", text)
    if not match:
        return text
    mantissa, exponent = match.group(1), int(match.group(2))
    return rf"\ensuremath{{{mantissa}\times10^{{{exponent}}}}}"


def _load():
    try:
        with open(JSON_FILE) as f:
            return json.load(f)
    except (FileNotFoundError, json.JSONDecodeError):
        return {}


def record(key, value, fmt="{:.4g}"):
    """Store one value for the paper; numbers are formatted with fmt, strings are used as they are."""
    if not _KEY.match(key):
        raise ValueError(f"paper key {key!r}: use letters, digits and '-', starting with a letter")
    if isinstance(value, (int, float, np.integer, np.floating)):
        text = latex_number(fmt.format(value))
    else:
        text = str(value)
    values = _load()
    values[key] = text
    os.makedirs(PAPER_DIR, exist_ok=True)
    with open(JSON_FILE, "w") as f:
        json.dump(values, f, indent=1, sort_keys=True)
    with open(TEX_FILE, "w") as f:
        f.write("% Generated by the scripts (common/report.py). Do not edit: rerun the part instead.\n")
        f.writelines(f"\\setvalue{{{k}}}{{{v}}}\n" for k, v in sorted(values.items()))


def record_system():
    """The seed and username, which every paper quotes."""
    from common.config import SEED, USERNAME
    record("seed", SEED, "{:d}")
    record("username", USERNAME.replace("_", r"\_"))


def record_many(values, fmt="{:.4g}"):
    """record() for a dict {key: value} or {key: (value, fmt)}."""
    for key, value in values.items():
        if isinstance(value, tuple):
            record(key, *value)
        else:
            record(key, value, fmt)
